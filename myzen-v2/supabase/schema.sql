-- ======================================================================
-- Desktop agent API (called with the PUBLIC anon key via supabase.rpc)
-- ======================================================================
-- The agent never holds the service-role key. It logs in with the employee's own email/password,
-- receives a random token (only its SHA-256 hash is stored), and every later call proves the token.
-- Each function derives employee_id from the token, so one PC can only read/write its own rows.

create table if not exists agent_tokens (
  token_hash  text primary key,
  employee_id uuid not null references employees(id) on delete cascade,
  machine_id  text,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null
);
create table if not exists login_failures (
  email text not null,
  at    timestamptz not null default now()
);
create index if not exists idx_login_failures on login_failures (email, at);
alter table agent_tokens   enable row level security;
alter table login_failures enable row level security;

create or replace function agent_login(p_email text, p_password text, p_machine text default null)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare e employees; tok text;
begin
  if (select count(*) from login_failures where email = lower(p_email) and at > now() - interval '10 minutes') >= 10 then
    return jsonb_build_object('error', 'too_many_attempts');
  end if;
  select * into e from employees
   where lower(email) = lower(p_email) and password_hash is not null and password_hash = crypt(p_password, password_hash);
  if not found then
    insert into login_failures (email) values (lower(p_email));
    delete from login_failures where at < now() - interval '1 day';
    return jsonb_build_object('error', 'invalid_credentials');
  end if;
  tok := encode(gen_random_bytes(32), 'hex');
  insert into agent_tokens (token_hash, employee_id, machine_id, expires_at)
    values (encode(digest(tok, 'sha256'), 'hex'), e.id, p_machine, now() + interval '30 days');
  delete from agent_tokens where expires_at < now();
  return jsonb_build_object(
    'token', tok,
    'employee', jsonb_build_object('id', e.id, 'name', e.name, 'email', e.email, 'role', e.role, 'department', e.department),
    'rules', coalesce((select jsonb_agg(jsonb_build_object('type', rule_type, 'pattern', pattern, 'category', category)) from app_category_rules), '[]'::jsonb),
    'config', coalesce((select jsonb_object_agg(config_key, config_value) from system_config), '{}'::jsonb)
  );
end $$;

create or replace function agent_employee(p_token text) returns uuid
language sql security definer stable set search_path = public, extensions as $$
  select employee_id from agent_tokens where token_hash = encode(digest(p_token, 'sha256'), 'hex') and expires_at > now();
$$;

create or replace function agent_logout(p_token text) returns void
language sql security definer set search_path = public, extensions as $$
  delete from agent_tokens where token_hash = encode(digest(p_token, 'sha256'), 'hex');
$$;

create or replace function agent_sync(p_token text, p_payload jsonb) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare emp uuid := agent_employee(p_token); s jsonb;
begin
  if emp is null then return jsonb_build_object('error', 'unauthorized'); end if;
  if jsonb_array_length(coalesce(p_payload->'sessions', '[]')) > 1000
     or jsonb_array_length(coalesce(p_payload->'punches', '[]')) > 200
     or jsonb_array_length(coalesce(p_payload->'breaks', '[]')) > 200
     or jsonb_array_length(coalesce(p_payload->'timesheet', '[]')) > 200
     or jsonb_array_length(coalesce(p_payload->'screenshots', '[]')) > 200 then
    return jsonb_build_object('error', 'payload_too_large');
  end if;

  insert into attendance_punches (id, employee_id, punch_type, punch_time)
    select (x->>'id')::uuid, emp, x->>'type', (x->>'time')::timestamptz from jsonb_array_elements(coalesce(p_payload->'punches', '[]')) x
  on conflict (id) do nothing;

  insert into breaks (id, employee_id, break_start, break_end, duration_minutes, break_type)
    select (x->>'id')::uuid, emp, (x->>'start')::timestamptz, (x->>'end')::timestamptz, (x->>'minutes')::int, coalesce(x->>'type', 'regular')
    from jsonb_array_elements(coalesce(p_payload->'breaks', '[]')) x
  on conflict (id) do update set break_end = excluded.break_end, duration_minutes = excluded.duration_minutes
    where breaks.employee_id = emp;

  insert into timesheet_entries (id, employee_id, entry_date, start_time, end_time, hours, description, entry_type)
    select (x->>'id')::uuid, emp, (x->>'date')::date, nullif(x->>'start', '')::time, nullif(x->>'end', '')::time,
           (x->>'hours')::numeric, left(x->>'description', 500), 'manual'
    from jsonb_array_elements(coalesce(p_payload->'timesheet', '[]')) x
  on conflict (id) do nothing;

  insert into activity_sessions (id, employee_id, start_time, end_time, app_name, url, category, is_active, duration_ms)
    select (x->>'id')::uuid, emp, (x->>'start')::timestamptz, (x->>'end')::timestamptz, left(x->>'app', 200), left(x->>'url', 200),
           x->>'category', coalesce((x->>'active')::boolean, true), (x->>'duration_ms')::bigint
    from jsonb_array_elements(coalesce(p_payload->'sessions', '[]')) x
  on conflict (id) do nothing;

  if coalesce((select config_value from system_config where config_key = 'screenshots_enabled'), 'false') = 'true' then
    insert into screenshots (id, employee_id, captured_at, app_name, local_file, storage_path, uploaded, blurred)
      select (x->>'id')::uuid, emp, (x->>'time')::timestamptz, left(x->>'app', 200), left(x->>'file', 200), null, false, false
      from jsonb_array_elements(coalesce(p_payload->'screenshots', '[]')) x
    on conflict (id) do nothing;
  end if;

  s := p_payload->'stats';
  if s is not null and s ? 'date' then
    insert into daily_stats (employee_id, stat_date, online_minutes, active_minutes, productive_minutes, unproductive_minutes,
                             idle_minutes, total_breaks_minutes, productivity_percentage, present)
    values (emp, (s->>'date')::date, (s->>'online')::int, (s->>'active')::int, (s->>'productive')::int, (s->>'unproductive')::int,
            (s->>'idle')::int, (s->>'breaks')::int, least(100, (s->>'pct')::numeric), true)
    on conflict (employee_id, stat_date) do update set
      online_minutes = excluded.online_minutes, active_minutes = excluded.active_minutes, productive_minutes = excluded.productive_minutes,
      unproductive_minutes = excluded.unproductive_minutes, idle_minutes = excluded.idle_minutes,
      total_breaks_minutes = excluded.total_breaks_minutes, productivity_percentage = excluded.productivity_percentage, present = true;
  end if;

  update employees set status = coalesce(nullif(p_payload->>'status', ''), status), last_seen = now(),
         machine_id = coalesce(p_payload->>'machine', machine_id)
   where id = emp and (p_payload->>'status') in ('online', 'away', 'offline');

  return jsonb_build_object('ok', true, 'server_time', now());
end $$;

-- The employee's own recent attendance, used by the desktop app to restore state and show timesheet history.
create or replace function agent_history(p_token text, p_days int default 30) returns jsonb
language plpgsql security definer stable set search_path = public, extensions as $$
declare emp uuid := agent_employee(p_token); since timestamptz := now() - make_interval(days => least(greatest(p_days, 1), 92));
begin
  if emp is null then return jsonb_build_object('error', 'unauthorized'); end if;
  return jsonb_build_object(
    'punches',   coalesce((select jsonb_agg(jsonb_build_object('id', id, 'type', punch_type, 'time', punch_time) order by punch_time) from attendance_punches where employee_id = emp and punch_time >= since), '[]'::jsonb),
    'breaks',    coalesce((select jsonb_agg(jsonb_build_object('id', id, 'start', break_start, 'end', break_end, 'minutes', duration_minutes, 'type', break_type) order by break_start) from breaks where employee_id = emp and break_start >= since), '[]'::jsonb),
    'timesheet', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'date', entry_date, 'start', start_time, 'end', end_time, 'hours', hours, 'description', description, 'approved', approved) order by entry_date) from timesheet_entries where employee_id = emp and entry_date >= since::date), '[]'::jsonb)
  );
end $$;

do $$
declare f text;
begin
  foreach f in array array[
    'agent_login(text,text,text)', 'agent_employee(text)', 'agent_logout(text)', 'agent_sync(text,jsonb)', 'agent_history(text,int)'
  ] loop
    -- Supabase's default privileges grant EXECUTE to anon/authenticated on new functions, so revoke explicitly first.
    execute format('revoke all on function %s from public', f);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on function %s from anon', f);
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
      execute format('revoke all on function %s from authenticated', f);
    end if;
    -- agent_employee is internal: only the security-definer functions above call it.
    if f <> 'agent_employee(text)' then
      if exists (select 1 from pg_roles where rolname = 'anon') then execute format('grant execute on function %s to anon', f); end if;
      if exists (select 1 from pg_roles where rolname = 'authenticated') then execute format('grant execute on function %s to authenticated', f); end if;
    end if;
    if exists (select 1 from pg_roles where rolname = 'service_role') then
      execute format('grant execute on function %s to service_role', f);
    end if;
  end loop;
end $$;
