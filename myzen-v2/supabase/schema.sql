-- MyZenV2 schema for Supabase (Postgres). Paste into the Supabase SQL editor and run once.
-- Safe to re-run: every object is created with IF NOT EXISTS / OR REPLACE.
--
-- Access model
--   * Every table has RLS enabled and NO policies for anon/authenticated roles, so the public anon key
--     can read or write nothing.
--   * The manager portal (server-side API routes) and the desktop agent both use the service-role key,
--     which bypasses RLS. Never ship the service-role key to a browser.
--   * Employees authenticate through verify_employee_login(), which is executable by service_role only.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- employees
create table if not exists employees (
  id            uuid primary key default gen_random_uuid(),
  email         text unique not null,
  name          text not null,
  password_hash text,
  department    text,
  role          text,
  is_manager    boolean not null default false,
  status        text not null default 'offline' check (status in ('online','away','offline')),
  last_seen     timestamptz,
  machine_id    text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- ------------------------------------------------- activity sessions (agent)
-- One row per contiguous stretch in one app/URL. Contains app name + optional URL only, never keystrokes.
create table if not exists activity_sessions (
  id          uuid primary key,                     -- generated by the agent so re-syncs are idempotent
  employee_id uuid not null references employees(id) on delete cascade,
  start_time  timestamptz not null,
  end_time    timestamptz,
  app_name    text,
  url         text,
  category    text not null check (category in ('productive','neutral','unproductive')),
  is_active   boolean not null default true,        -- false = idle (no input for idle threshold)
  duration_ms bigint not null default 0,
  created_at  timestamptz not null default now()
);

-- ------------------------------------------------------------- attendance
create table if not exists attendance_punches (
  id          uuid primary key default gen_random_uuid(),
  employee_id uuid not null references employees(id) on delete cascade,
  punch_type  text not null check (punch_type in ('in','out')),
  punch_time  timestamptz not null,
  notes       text,
  created_at  timestamptz not null default now()
);

create table if not exists breaks (
  id               uuid primary key default gen_random_uuid(),
  employee_id      uuid not null references employees(id) on delete cascade,
  break_start      timestamptz not null,
  break_end        timestamptz,
  duration_minutes integer,
  break_type       text not null default 'regular',
  created_at       timestamptz not null default now()
);

-- Manual "log time" entries made from the desktop app (e.g. meetings off-computer, missed punches).
create table if not exists timesheet_entries (
  id          uuid primary key default gen_random_uuid(),
  employee_id uuid not null references employees(id) on delete cascade,
  entry_date  date not null,
  start_time  time,
  end_time    time,
  hours       numeric(5,2) not null check (hours > 0 and hours <= 24),
  description text,
  entry_type  text not null default 'manual',
  approved    boolean not null default false,
  created_at  timestamptz not null default now()
);

-- ------------------------------------------------------- rules + aggregates
-- rule_type 'app' matches the foreground app name (substring, case-insensitive);
-- 'domain' matches the browser URL host. Agent loads these at start-up when Supabase is configured.
create table if not exists app_category_rules (
  id         uuid primary key default gen_random_uuid(),
  rule_type  text not null check (rule_type in ('app','domain')),
  pattern    text not null,
  category   text not null check (category in ('productive','neutral','unproductive')),
  created_at timestamptz not null default now(),
  unique (rule_type, pattern)
);

create table if not exists daily_stats (
  id                      uuid primary key default gen_random_uuid(),
  employee_id             uuid not null references employees(id) on delete cascade,
  stat_date               date not null,
  online_minutes          integer not null default 0,
  active_minutes          integer not null default 0,
  productive_minutes      integer not null default 0,
  unproductive_minutes    integer not null default 0,
  idle_minutes            integer not null default 0,
  total_breaks_minutes    integer not null default 0,
  productivity_percentage numeric(5,2) not null default 0,
  present                 boolean not null default false,
  updated_at              timestamptz not null default now(),
  unique (employee_id, stat_date)
);

-- --------------------------------------- screenshots (feature OFF by default)
-- The agent syncs METADATA ONLY (when, which app, local file name). Image upload to a private Storage
-- bucket is not implemented, so storage_path stays null and uploaded=false. agent_sync ignores screenshot
-- rows unless system_config.screenshots_enabled = 'true'. `blurred` is false because no blurring exists yet.
create table if not exists screenshots (
  id             uuid primary key default gen_random_uuid(),
  employee_id    uuid not null references employees(id) on delete cascade,
  storage_path   text,
  captured_at    timestamptz not null,
  app_name       text,
  blurred        boolean not null default false,
  created_at     timestamptz not null default now()
);
alter table screenshots alter column storage_path drop not null;
alter table screenshots alter column blurred set default false;
alter table screenshots add column if not exists local_file text;
alter table screenshots add column if not exists uploaded boolean not null default false;
create index if not exists screenshots_employee_time on screenshots (employee_id, captured_at desc);

create table if not exists system_config (
  config_key   text primary key,
  config_value text not null,
  description  text,
  updated_at   timestamptz not null default now()
);

-- ----------------------------------------------------------------- indexes
create index if not exists idx_sessions_emp_start  on activity_sessions (employee_id, start_time);
create index if not exists idx_punches_emp_time    on attendance_punches (employee_id, punch_time);
create index if not exists idx_breaks_emp_start    on breaks (employee_id, break_start);
create index if not exists idx_timesheet_emp_date  on timesheet_entries (employee_id, entry_date);
create index if not exists idx_daily_stats_date    on daily_stats (stat_date);

