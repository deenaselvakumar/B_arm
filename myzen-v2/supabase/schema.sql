-- --------------------------------------------------------------- functions
create or replace function set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists trg_employees_updated on employees;
create trigger trg_employees_updated before update on employees
  for each row execute function set_updated_at();

drop trigger if exists trg_daily_stats_updated on daily_stats;
create trigger trg_daily_stats_updated before update on daily_stats
  for each row execute function set_updated_at();

create or replace function set_employee_password(p_email text, p_password text)
returns void language sql security definer set search_path = public, extensions as $$
  update employees set password_hash = crypt(p_password, gen_salt('bf', 10)) where lower(email) = lower(p_email);
$$;

create or replace function verify_employee_login(p_email text, p_password text)
returns table (id uuid, name text, email text, role text, department text, is_manager boolean)
language sql security definer set search_path = public, extensions as $$
  select e.id, e.name, e.email, e.role, e.department, e.is_manager
  from employees e
  where lower(e.email) = lower(p_email)
    and e.password_hash is not null
    and e.password_hash = crypt(p_password, e.password_hash);
$$;

do $$
declare r text;
begin
  revoke all on function set_employee_password(text, text) from public;
  revoke all on function verify_employee_login(text, text) from public;
  foreach r in array array['anon','authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on function set_employee_password(text, text) from %I', r);
      execute format('revoke all on function verify_employee_login(text, text) from %I', r);
    end if;
  end loop;
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant execute on function set_employee_password(text, text) to service_role;
    grant execute on function verify_employee_login(text, text) to service_role;
  end if;
end $$;

